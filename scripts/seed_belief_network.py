"""End-to-end: load YAML seeds → decompose → consolidate → render viz.

Steps:
  1. Parse design_docs/internal_links_seed_v0.yaml
  2. For each entry, upsert StateBelief and InternalLink records into Neo4j
  3. Run BeliefDecomposer over the seed premises (budget=100 Sonnet calls)
  4. Run consolidate() on the resulting graph
  5. Render the static-network viz

After this script: Neo4j has the full hand-seeded + decomposed + consolidated
belief network, and viz_beliefs/latest.html shows it.
"""
